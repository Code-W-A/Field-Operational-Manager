import { test, expect } from "@playwright/test"

test("a sent offer opens as a separate editable draft and preserves its original snapshot", async ({ page }) => {
  await page.addInitScript(() => {
    document.addEventListener("DOMContentLoaded", () => {
      const style = document.createElement("style")
      style.textContent = '[data-testid="preview-mode-banner"] { display:none !important; }'
      document.head.appendChild(style)
    })
  })
  let issued = 0
  await page.route("**/api/crm/offers/issue", (route) => { issued++; return route.abort() })
  await page.route("https://firebasestorage.googleapis.com/**", (route) => route.abort())
  await page.goto("/crm/opportunities/e2e-opp-offers/offers")
  const reuse = page.getByTestId("offer-reuse-e2e-offer-sent")
  await reuse.click()
  const dialog = page.getByRole("dialog", { name: "Editor ofertă", exact: true })
  await expect(dialog.getByText("Ofertă nouă pornind de la V3.", { exact: false })).toBeVisible()
  await expect(dialog.locator("#name-p1")).toHaveValue("Barieră automată 6m")
  await expect(dialog.locator("#name-o1")).toHaveValue("Iluminat LED pe braț")
  await expect(dialog.locator("#offer-vat")).toHaveValue("19")
  await expect(dialog.locator("#offer-adjustment")).toHaveValue("-10")
  await expect(dialog.locator("#offer-validity")).toHaveValue("15 zile de la emitere")
  await expect(dialog.locator("#offer-terms-payment")).toHaveValue("conform contract")
  await expect(dialog.locator("#offer-terms-delivery")).toHaveValue("30 zile lucrătoare")
  await expect(dialog.locator("#offer-terms-installation")).toHaveValue("nu este inclusă")
  await expect(dialog.locator("#offer-comments")).toHaveValue("Note interne ofertă trimisă")
  await expect(dialog.locator("#offer-email-subject")).toHaveValue("Ofertă transmisă V3")
  await expect(dialog.locator("#offer-email-body")).toHaveValue("Mesaj ofertă transmisă")
  await dialog.locator("#name-p1").fill("Barieră modificată")
  await dialog.locator("#offer-email-subject").fill("Ofertă revizuită")
  await dialog.getByRole("button", { name: "Salvează draft" }).click()
  await expect(page.getByText("Draft salvat", { exact: true })).toBeVisible()
  await dialog.getByRole("button", { name: "Close", exact: true }).click()
  const newDraft = page.getByTestId("offer-load-draft-e2e-offer-4")
  await expect(newDraft).toBeVisible()
  await reuse.click()
  await expect(dialog.locator("#name-p1")).toHaveValue("Barieră automată 6m")
  await expect(dialog.locator("#offer-email-subject")).toHaveValue("Ofertă transmisă V3")
  await expect(dialog.locator("#offer-vat")).toHaveValue("19")
  await dialog.getByRole("button", { name: "Close", exact: true }).click()
  await newDraft.click()
  await expect(dialog.locator("#name-p1")).toHaveValue("Barieră modificată")
  await expect(dialog.locator("#offer-email-subject")).toHaveValue("Ofertă revizuită")
  await expect(dialog.locator("#offer-vat")).toHaveValue("19")
  expect(issued).toBe(0)
})
